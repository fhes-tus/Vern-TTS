"""Regenerate launcher/splash variants and manifest entry points from Kotlin's palette list."""
from pathlib import Path
import re

root = Path(__file__).resolve().parents[1] / 'app/src/main'
source = (root/'java/com/veritas/reader/VernCustomization.kt').read_text(encoding='utf-8')
palettes = re.findall(r'VernIconPalette\("([a-z]+)", "[^"]+", 0xFF([A-F0-9]{6})\.toInt\(\), 0xFF([A-F0-9]{6})\.toInt\(\)\)', source)
assert len(palettes) >= 6 and len({p[0] for p in palettes}) == len(palettes)
res = root/'res'
fg = (res/'drawable/vern_icon_foreground.xml').read_text(encoding='utf-8')
bg = (res/'drawable/vern_icon_background.xml').read_text(encoding='utf-8')
splash = (res/'drawable/vern_splash_mark.xml').read_text(encoding='utf-8')
animated = (res/'drawable/vern_splash_animated.xml').read_text(encoding='utf-8')
adaptive = (res/'mipmap-anydpi-v26/ic_launcher.xml').read_text(encoding='utf-8')
classes = ['package com.veritas.reader', '', '// Generated by tools/generate_vern_startup_resources.py.']
activities, aliases, styles, native_styles = [], [], ['<resources>'], ['<resources>']
for id, background, foreground in palettes:
    suffix = '' if id == 'indigo' else '_'+id
    title = id.title()
    icon = 'ic_launcher' if id == 'indigo' else 'vern_launcher_'+id
    if suffix:
        (res/f'drawable/vern_icon_foreground{suffix}.xml').write_text(fg.replace('#FFF6E6', '#'+foreground), encoding='utf-8')
        (res/f'drawable/vern_icon_background{suffix}.xml').write_text(bg.replace('#4540D8', '#'+background), encoding='utf-8')
        (res/f'drawable/vern_splash_mark{suffix}.xml').write_text(splash.replace('#FFF6E6', '#'+foreground), encoding='utf-8')
        (res/f'drawable/vern_splash_animated{suffix}.xml').write_text(animated.replace('@drawable/vern_splash_mark', '@drawable/vern_splash_mark'+suffix), encoding='utf-8')
        (res/f'mipmap-anydpi-v26/{icon}.xml').write_text(adaptive.replace('@drawable/vern_icon_foreground', '@drawable/vern_icon_foreground'+suffix).replace('@drawable/vern_icon_background', '@drawable/vern_icon_background'+suffix), encoding='utf-8')
    (res/f'drawable/vern_starting_mark_{id}.xml').write_text(fg.replace('#FFF6E6', '#'+foreground).replace('108dp', '192dp'), encoding='utf-8')
    (res/f'drawable/vern_starting_window_{id}.xml').write_text(f'''<layer-list xmlns:android="http://schemas.android.com/apk/res/android">
    <item android:drawable="@drawable/vern_icon_background{suffix}" />
    <item android:drawable="@drawable/vern_starting_mark_{id}" android:gravity="center" android:width="192dp" android:height="192dp" />
</layer-list>
''', encoding='utf-8')
    for static in ['', 'Static']:
        target = '.MainActivity' if id == 'indigo' and not static else f'.Startup{title}{static}Activity'
        if target != '.MainActivity':
            classes.append(f'class {target[1:]} : MainActivity()')
            activities.append(f'        <activity android:name="{target}" android:exported="false" android:theme="@style/Theme.Vern.Startup{title}{static}" android:icon="@mipmap/{icon}" android:configChanges="keyboardHidden|orientation|screenSize|screenLayout|smallestScreenSize" android:windowSoftInputMode="adjustResize" />')
        enabled = 'true' if id == 'indigo' and not static else 'false'
        aliases.append(f'''        <activity-alias android:name=".Launcher{title}{static}" android:targetActivity="{target}"
            android:enabled="{enabled}" android:exported="true" android:icon="@mipmap/{icon}" android:roundIcon="@mipmap/{icon}" android:label="@string/app_name">
            <intent-filter><action android:name="android.intent.action.MAIN" /><category android:name="android.intent.category.LAUNCHER" /></intent-filter>
        </activity-alias>''')
        styles.append(f'''    <style name="Theme.Vern.Startup{title}{static}" parent="Theme.Vern">
        <item name="android:windowBackground">@drawable/vern_starting_window_{id}</item>
    </style>''')
        drawable = 'vern_splash_mark' if static else 'vern_splash_animated'
        native_styles.append(f'''    <style name="Theme.Vern.Startup{title}{static}" parent="Theme.Vern">
        <item name="android:windowSplashScreenBackground">#{background}</item>
        <item name="android:windowSplashScreenAnimatedIcon">@drawable/{drawable}{suffix}</item>
        <item name="android:windowSplashScreenAnimationDuration">950</item>
    </style>''')
styles.append('</resources>'); native_styles.append('</resources>')
(res/'values/vern_startup_styles.xml').write_text('\n'.join(styles)+'\n', encoding='utf-8')
(res/'values-v31/vern_startup_styles.xml').write_text('\n'.join(native_styles)+'\n', encoding='utf-8')
(root/'java/com/veritas/reader/VernStartupActivities.kt').write_text('\n'.join(classes)+'\n', encoding='utf-8')
manifest = root/'AndroidManifest.xml'
text = manifest.read_text(encoding='utf-8')
text = re.sub(r'        <!-- BEGIN VERN LAUNCHERS -->.*?        <!-- END VERN LAUNCHERS -->\s*', '', text, flags=re.S)
text = re.sub(r'^[ \t]*<activity android:name="\.Startup[A-Z][A-Za-z]*Activity"[^\n]*/>[ \t]*\n?', '', text, flags=re.M)
text = re.sub(r'^[ \t]*<activity-alias android:name="\.Launcher[A-Z][A-Za-z]*".*?</activity-alias>[ \t]*\n?', '', text, flags=re.M|re.S)
marker = '        <activity-alias\n            android:name=".ShareToNotesActivity"'
text = re.sub(r'^[ \t]*(<activity-alias\n[ \t]*android:name="\.ShareToNotesActivity")', r'        \1', text, flags=re.M)
assert marker in text
block = '\n'.join(['        <!-- BEGIN VERN LAUNCHERS -->']+activities+aliases+['        <!-- END VERN LAUNCHERS -->', ''])
text = text.replace(marker, block+'\n'+marker, 1)
manifest.write_text(text, encoding='utf-8')
print(f'Generated {len(palettes)} icon palettes and {len(aliases)} matching launcher/splash entries.')
